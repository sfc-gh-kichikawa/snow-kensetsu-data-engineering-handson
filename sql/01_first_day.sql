/* =====================================================================
   第1章 9:00 初出社：CoCo と出会う
   ---------------------------------------------------------------------
   CoCo には、画面右のチャット欄から頼みます。
   SQL をファイルに書いてほしいときは、指示の最後に
   「〇〇の下に追記してください。実行はしないでください。」と付けます。
   下の「CoCo への指示」をコピーして、チャット欄に貼り付けてください。
   ===================================================================== */

/* ---------------------------------------------------------------------
   ① アカウントの中を見てみる
   CONSTRUCTION_HOL は、今日のハンズオン用に用意した Snow建設のデータベースです。
   中のテーブルを、CoCo に日本語で説明してもらいます。
   CoCo は、テーブルの名前や列、件数を実際に調べたうえで答えます。

   CoCo への指示（コピーして送る）：

   CONSTRUCTION_HOL のテーブルを、日本語で簡単に説明してください。
   --------------------------------------------------------------------- */


/* ---------------------------------------------------------------------
   ② ウェアハウスを作る
   ウェアハウスは、SQL を実行する「計算のエンジン」です。データは別の場所に保存されているので、
   同じデータに対して、用途ごとにウェアハウスを分けて作れます。
     ・ETL_WH：IICS から届いたデータの取り込みや加工に使う
     ・BI_WH ：Power BI など、データを見る側の問い合わせに使う
   分けておくと、加工の処理が重くても、見る側の速さに影響しません。
   XSMALL は一番小さいサイズです。60秒使われなければ自動で止まり、止まっている間は料金がかかりません。
   次に SQL が来れば、自動で動き出します。

   CoCo への指示（コピーして送る）：

   ETL用の ETL_WH と BI用の BI_WH を作るSQLを、②の下に追記してください。サイズは XSMALL、60秒で自動停止です。実行はしないでください。

   CoCo が追記した SQL を確認してから、自分で実行（Ctrl + Enter）してください。
   --------------------------------------------------------------------- */


/* ---------------------------------------------------------------------
   ③ わからないことを聞いてみる
   わからない言葉が出てきたら、その場で CoCo に聞けます。CoCo は公式ドキュメントをもとに答えます。

   CoCo への指示（コピーして送る）：

   マイクロパーティションとは何ですか？Azure SQL Database のインデックスとの違いを、初心者向けに説明してください。
   --------------------------------------------------------------------- */


/* ---------------------------------------------------------------------
   ④ 作ったウェアハウスを確認する（この文だけ実行してください）
   SHOW WAREHOUSES だけだと、アカウントにあるすべてのウェアハウスが表示されます。
   ここでは「->>」で SHOW の結果を SELECT に渡し、ETL_WH と BI_WH だけに絞っています。
   見るところ：size が X-Small、auto_suspend が 60、auto_resume が true になっていること。
   --------------------------------------------------------------------- */
SHOW WAREHOUSES
  ->> SELECT "name", "state", "size", "auto_suspend", "auto_resume", "comment"
      FROM $1
      WHERE "name" IN ('ETL_WH', 'BI_WH');

/* =====================================================================
   第4章　12:00 明日の朝ピークに備える
   ---------------------------------------------------------------------
   経理部長「毎朝7時半から9時は、レポートが遅くて仕事にならない」

     ① 同じクエリを XS と S で実行して、時間を比べる
     ② 同じクエリをもう一度実行して、結果キャッシュを体験する
     ③ 使っていないウェアハウスが止まっていることを確かめる
   ===================================================================== */

USE WAREHOUSE BI_WH;

-- ---------------------------------------------------------------------
-- ① サイズによる違いを体感する
-- ---------------------------------------------------------------------
-- 結果キャッシュ：同じ SQL を同じデータに実行したとき、前の結果をそのまま返す仕組みです。
-- 有効のままだと2回目以降が一瞬で終わってしまい、サイズの違いを比べられません。
-- 公平に比べるため、このセッションだけ結果キャッシュを無効にします
ALTER SESSION SET USE_CACHED_RESULT = FALSE;

-- 約6億行の注文明細（TPC-H のサンプルデータ）を集計します。
-- TPC-H は、データベースの性能比較でよく使われる架空の注文データです。どのアカウントにも入っています。
-- 実行後、結果の上に表示される所要時間をメモしてください（XS）。
SELECT
    l_returnflag,
    l_linestatus,
    SUM(l_quantity)                                       AS sum_qty,
    SUM(l_extendedprice)                                  AS sum_base_price,
    SUM(l_extendedprice * (1 - l_discount))               AS sum_disc_price,
    SUM(l_extendedprice * (1 - l_discount) * (1 + l_tax)) AS sum_charge,
    AVG(l_discount)                                       AS avg_disc,
    COUNT(*)                                              AS count_order
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF100.LINEITEM
WHERE l_shipdate <= DATEADD(day, -90, '1998-12-01'::DATE)
GROUP BY l_returnflag, l_linestatus
ORDER BY l_returnflag, l_linestatus;

-- ウェアハウスのサイズは、1つ上げるごとに計算の力と1時間あたりの料金が2倍になります。
-- 処理時間がおよそ半分になれば、かかる料金はほぼ同じで、結果が早く返ります。
-- サイズの変更は止めずにすぐ反映され、次に実行するクエリから新しいサイズで動きます。

-- 【CoCoへの指示】
--   BI_WH のサイズを S に変更してください。

-- 変更したら、上の同じクエリをもう一度実行して、時間を比べてください（S）。


-- ---------------------------------------------------------------------
-- ② 結果キャッシュ
-- ---------------------------------------------------------------------
-- 結果キャッシュを有効に戻して、上の同じクエリをもう2回実行してください。
-- 1回目は、キャッシュを無効にしていた間の結果が使えないので、もう一度計算します。
-- 2回目は、一瞬で結果が返ります（ウェアハウスは動いていません）。
-- 結果キャッシュは24時間残り、元のデータが変わると使われなくなります。
-- 朝の時間帯に同じレポートを何人も開く場合、2人目からは計算せずに結果が返ります。
ALTER SESSION SET USE_CACHED_RESULT = TRUE;


-- 終わったら、サイズを XS に戻しておきます
ALTER WAREHOUSE BI_WH SET WAREHOUSE_SIZE = 'XSMALL';


-- ---------------------------------------------------------------------
-- ③ 使っていないウェアハウスは止まっている
-- ---------------------------------------------------------------------
-- state 列を見てください。しばらく使っていない ETL_WH は SUSPENDED（停止中＝課金なし）です。
-- 第1章で「60秒使われなければ自動で止まる」ように作ったためです。
-- 動いている時間（秒単位、最初の1分は最低料金）だけ料金がかかります。
SHOW WAREHOUSES
  ->> SELECT "name", "state", "size" FROM $1 WHERE "name" IN ('ETL_WH', 'BI_WH');

   救済用の正解SQL（第4章〜第5章）
   ===================================================================== */

USE ROLE ACCOUNTADMIN;
USE SCHEMA CONSTRUCTION_HOL.RAW;
USE WAREHOUSE BI_WH;

-- =====================================================================
-- 第4章 サイズを変える
-- =====================================================================
ALTER WAREHOUSE BI_WH SET WAREHOUSE_SIZE = 'SMALL';
-- 終わったら元に戻す
ALTER WAREHOUSE BI_WH SET WAREHOUSE_SIZE = 'XSMALL';

-- =====================================================================
-- 第5章 守りの運用
-- =====================================================================

-- ② ゼロコピークローン
CREATE SCHEMA IF NOT EXISTS CONSTRUCTION_HOL.DEV COMMENT = '開発環境';
CREATE OR REPLACE TABLE CONSTRUCTION_HOL.DEV.COST_DETAIL CLONE CONSTRUCTION_HOL.RAW.COST_DETAIL;

-- ③ 行アクセスポリシー
CREATE OR REPLACE ROW ACCESS POLICY CONSTRUCTION_HOL.RAW.BRANCH_RAP
  AS (branch_value VARCHAR) RETURNS BOOLEAN ->
    CURRENT_ROLE() = 'ACCOUNTADMIN'
    OR EXISTS (
      SELECT 1
      FROM CONSTRUCTION_HOL.RAW.BRANCH_ROLE_MAP m
      WHERE m.ROLE_NAME = CURRENT_ROLE()
        AND m.BRANCH = branch_value
    );

ALTER TABLE CONSTRUCTION_HOL.RAW.COST_DETAIL
  ADD ROW ACCESS POLICY CONSTRUCTION_HOL.RAW.BRANCH_RAP ON (BRANCH);

-- ④ マスキングポリシー
CREATE OR REPLACE MASKING POLICY CONSTRUCTION_HOL.RAW.SALARY_MASK
  AS (val NUMBER) RETURNS NUMBER ->
    CASE WHEN CURRENT_ROLE() = 'HR_ROLE' THEN val ELSE NULL END;

ALTER TABLE CONSTRUCTION_HOL.RAW.EMPLOYEES
  MODIFY COLUMN MONTHLY_SALARY SET MASKING POLICY CONSTRUCTION_HOL.RAW.SALARY_MASK;

-- ⑤ 監査の準備：参照できるロールの一覧
SHOW GRANTS ON TABLE CONSTRUCTION_HOL.RAW.EMPLOYEES;

-- ⑤ 監査の準備：設定されているポリシーの一覧
SELECT POLICY_NAME, POLICY_KIND, REF_COLUMN_NAME, POLICY_STATUS
FROM TABLE(CONSTRUCTION_HOL.INFORMATION_SCHEMA.POLICY_REFERENCES(
  REF_ENTITY_NAME => 'CONSTRUCTION_HOL.RAW.EMPLOYEES',
  REF_ENTITY_DOMAIN => 'table'));

-- ⑤ 監査の準備：Time Travel で10分前の支店別原価
SELECT BRANCH, SUM(AMOUNT) AS TOTAL_COST
FROM CONSTRUCTION_HOL.RAW.COST_DETAIL AT (OFFSET => -60 * 10)
GROUP BY BRANCH
ORDER BY BRANCH;

-- ⑥ リソースモニター
CREATE OR REPLACE RESOURCE MONITOR HOL_MONITOR
  WITH CREDIT_QUOTA = 5
  FREQUENCY = DAILY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND;

ALTER WAREHOUSE ETL_WH SET RESOURCE_MONITOR = HOL_MONITOR;
ALTER WAREHOUSE BI_WH  SET RESOURCE_MONITOR = HOL_MONITOR;
